// Test vectors generated using monero-wallet-cli v0.18.4.5
// Each mnemonic was generated by wallet-cli and verified against the spend key.

func TestMnemonicVectors(t *testing.T) {
	tests := []struct {
		name     string
		mnemonic string
		keyHex   string
	}{
		{
			name:     "mainnet",
			mnemonic: "skater fountain lair oars delayed lopped pause duckling lumber exit jingle until dolphin ought ramped makeup adept joking optical abrasive ability puddle popular rockets makeup",
			keyHex:   "83aaa12a23059f50c63e1a4b11589675aef480122951a66f7eeeaaffba16060e",
		},
		{
			name:     "testnet",
			mnemonic: "factual rage vibrate psychic maps mighty phone joyous duke sensible fifteen psychic ringing rally tarnished tiers atrium elope toxic answers eternal kisses eternal ferry vibrate",
			keyHex:   "59cfae3d4d6a99038b7844c5d61b5d6350077423f013512c19232f37669dcc05",
		},
		{
			name:     "stagenet",
			mnemonic: "anvil fudge syndrome luggage reruns syllabus lava memoir weird fungal maverick thumbs aplomb gourmet equip upgrade jabbed mirror pairing desk injury dawn tinted uptight anvil",
			keyHex:   "9710f183e594b61c93bdca6ea485de53a794cde8d955df1a7ab0d138b102c30e",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			// Test MnemonicToKey
			key, lang, err := MnemonicToKey(tt.mnemonic)
			if err != nil {
				t.Fatalf("MnemonicToKey() failed: %v", err)
			}
			if hex.EncodeToString(key[:]) != tt.keyHex {
				t.Errorf("MnemonicToKey() = %s, want %s", hex.EncodeToString(key[:]), tt.keyHex)
			}
			if lang != "english" {
				t.Errorf("MnemonicToKey() language = %s, want english", lang)
			}

			// Test KeyToMnemonic
			keyBytes, _ := hex.DecodeString(tt.keyHex)
			var keyArr [32]byte
			copy(keyArr[:], keyBytes)
			mnemonic, err := KeyToMnemonic(keyArr, "english")
			if err != nil {
				t.Fatalf("KeyToMnemonic() failed: %v", err)
			}
			if mnemonic != tt.mnemonic {
				t.Errorf("KeyToMnemonic() = %s, want %s", mnemonic, tt.mnemonic)
			}
		})
	}
}

func TestMnemonicRoundtrip(t *testing.T) {
	// Generate a key and verify mnemonic roundtrip
	key, err := NewKey(NetworkMainnet)
	if err != nil {
		t.Fatalf("NewKey() failed: %v", err)
	}

	mnemonic, err := key.Mnemonic("english")
	if err != nil {
		t.Fatalf("Mnemonic() failed: %v", err)
	}
	words := strings.Fields(mnemonic)
	if len(words) != 25 {
		t.Errorf("Mnemonic should have 25 words, got %d", len(words))
	}

	// Recover key from mnemonic
	recoveredKey, lang, err := MnemonicToKey(mnemonic)
	if err != nil {
		t.Fatalf("MnemonicToKey() failed: %v", err)
	}
	if lang != "english" {
		t.Errorf("MnemonicToKey() language = %s, want english", lang)
	}

	if recoveredKey != key.PrivateSpendKey {
		t.Error("Roundtrip failed: recovered key doesn't match original")
	}
}

