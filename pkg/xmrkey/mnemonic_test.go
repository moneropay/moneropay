func TestMultiLanguageMnemonic(t *testing.T) {
	// Generate a new key
	key, err := NewKey(NetworkMainnet)
	if err != nil {
		t.Fatalf("Failed to generate key: %v", err)
	}

	// Test all available languages
	for langName := range Languages {
		t.Run(langName, func(t *testing.T) {
			// Convert key to mnemonic in this language
			mnemonic, err := key.Mnemonic(langName)
			if err != nil {
				t.Fatalf("Failed to convert key to mnemonic: %v", err)
			}

			// Recover key from mnemonic (with auto-detection)
			recovered, err := NewKeyFromMnemonic(mnemonic, NetworkMainnet)
			if err != nil {
				t.Fatalf("Failed to recover key from mnemonic: %v", err)
			}

			// Verify the recovered key matches
			if recovered.Address != key.Address {
				t.Errorf("Address mismatch: got %s, want %s", recovered.Address, key.Address)
			}
		})
	}
}

func TestUnknownLanguage(t *testing.T) {
	key, err := NewKey(NetworkMainnet)
	if err != nil {
		t.Fatalf("Failed to generate key: %v", err)
	}

	_, err = key.Mnemonic("klingon")
	if !errors.Is(err, ErrUnknownLanguage) {
		t.Errorf("Expected ErrUnknownLanguage, got %v", err)
	}
}

func TestAvailableLanguages(t *testing.T) {
	languages := AvailableLanguages()
	if len(languages) != len(Languages) {
		t.Errorf("Expected %d languages, got %d", len(Languages), len(languages))
	}

	// Check that all expected languages are present
	expected := []string{"english", "spanish", "japanese", "russian", "german", "french", "italian", "dutch", "portuguese", "esperanto", "lojban", "chinesesimplified", "englishold"}
	for _, exp := range expected {
		found := false
		for _, lang := range languages {
			if lang == exp {
				found = true
				break
			}
		}
		if !found {
			t.Errorf("Expected language %s not found in available languages", exp)
		}
	}
}
